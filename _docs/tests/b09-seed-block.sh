# Contracted in from an AC block as: decode the base64 payload below into
# `_b09_seed_probe.py` in the caller's cwd, then import it. No other interface.
#
# This file carries ZERO verdict markers, and that is load-bearing rather than tidy:
# `runacs` grades the FIRST verdict-shaped line a block emits, so a marker spelled
# out in a file that an AC block decodes and then imports would let an unrelated
# AC read red while the subject under test printed nothing (B-07 R4's finding).
# The AC block owns the verdict. That is also why the payload is base64 rather
# than plain text: the payload's own docstrings name the states and statuses this
# issue counts, and base64 guarantees no marker can appear here by accident, now
# or after a later edit regenerates the block from `_docs/tests/b09-seed-payload.py`.
#
# The payload's one module-level side effect is a DATABASE_URL default.
# `app.database` builds its engine at import time from `app.config`, so a probe
# that sets the URL after any app import keeps the ambient database and counts
# rows in someone else's file. `setdefault` leaves an exported URL alone.
#
# `boot()` must run before `TestClient` is constructed. `app.main`'s lifespan runs
# `create_all` plus `bootstrap_defaults` against `app.database.engine` the first
# time a client is entered, so seeding a branch row first makes that INSERT
# collide on the primary key (measured: IntegrityError on `restaurants.id`).
# `boot()`'s own branch row is the one `bootstrap_defaults` leaves alone, because
# its guard is `count == 0`.
